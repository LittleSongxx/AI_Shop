-- ============================================================
-- 类目 + 属性定义种子数据
--
-- 为什么需要这个文件：generate_products.sql 第 30 行从 sys_category
-- 读二级类目填充临时表，但全仓库没有任何 sys_category 的 INSERT。
-- 结果是干净库上跑完初始化，临时表为空、循环不执行、商品表 0 条。
-- 这个文件补上那份缺失的前提。
--
-- 二级类目名对齐 AI_Shop-agent/app/config/search_taxonomy.yml 的 12 个
-- canonical（零食/手机/电脑/耳机/平板/相机/手表/玩具/乐器/家电/服饰/美妆）。
-- 对齐的意义：canonical 会直接变成 ES 查询串，类目名和它一致时，
-- 品类召回（load_by_category）和关键词召回（BM25）才指向同一批商品。
--
-- 属性名只用 generate_products.sql 的 temp_property_options 里已有的类型，
-- 否则那个脚本查不到候选值，会给商品生成空属性。
--
-- 用法: mysql -u<user> -p<pass> aishop_product < 01_category_seed.sql
-- 幂等：全部 INSERT IGNORE，可重复执行。
-- ============================================================

